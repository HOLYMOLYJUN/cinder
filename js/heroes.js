/* 잠긴 사람을 여는 열쇠. 지금은 「모두의 탑」 하나뿐이다.
   업적을 그대로 조건으로 쓴다 — 따로 세지 않아야 둘이 어긋날 일이 없다. */
function heroUnlocked(h) {
  if (!h.hidden) return true;
  const save = loadData() || {};
  return (save.achievements || []).includes('allHeroes');
}

// 고르는 자리에 나오는 사람들
function pickableHeroes() {
  return HEROES.filter(heroUnlocked);
}

